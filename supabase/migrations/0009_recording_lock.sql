-- ============================================================
--  録音ロック（ネイティブ版の音声メモ用）
-- ============================================================
--  ネイティブ版は音声メモの録音中、文字起こしを本文に一切書き込まず、
--  録音が終わったときに一度だけまとめて貼り付ける（IME・カーソルを
--  壊さないため）。その代わり、貼り付けるまでの間に他端末が同じメモを
--  編集していると、貼り付けた瞬間にどちらかの編集が消えてしまう。
--
--  これを防ぐため、「いまどの端末が録音しているか」を notes に持たせる。
--  サーバー側では拒否しない。両クライアントがこの値を見て編集を控える、
--  という取り決め（アプリ側の合意であり、DB制約ではない）。
--
--   recording_lock_by    … 録音中の端末ID（端末ごとのUUID。ユーザーIDではない）
--   recording_lock_until … ロックの期限（録音中の端末が25秒ごとに now()+60秒へ延長）
--
--  Web版は常にこの2カラムを読んで従うだけで、書き込むことはない
--  （lib/store.tsx の updateNote が唯一の保存経路で、常にこの2カラムを除外する）。
--
--  0006 の set_updated_at() は「内容列（title/body/type/status/tags/
--  expires_at/trashed_at）が1つも変わらなければ updated_at を据え置く」
--  という条件のため、この2カラムは対象外＝この2カラムだけの更新
--  （ロックの取得・延長・解除）では updated_at は動かない。トリガーの
--  変更は不要。
--
--  このマイグレーションは冪等（何度実行しても安全）。
-- ============================================================
alter table public.notes
  add column if not exists recording_lock_by uuid,
  add column if not exists recording_lock_until timestamptz;
